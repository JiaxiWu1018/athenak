"""Validate the report pipeline against completed, audited native segments only."""
import json,os,subprocess,sys
from pathlib import Path
import numpy as np
import pandas as pd

root=Path(os.environ['SESSION_ROOT'])
tooling=Path(os.environ['TOOLING_DIR']);sys.path.insert(0,str(tooling))
import products
products.require_compute()
qa=json.loads((root/'evidence/render_qa_474151/RESULT.json').read_text())
assert qa['status']=='pass'
assert products.sha256(tooling/'products.py')==qa['tooling_sha256']['products.py']
out=root/'evidence'/f'real_report_{os.environ["SLURM_JOB_ID"]}';out.mkdir()
view=out/'completed_input';(view/'runs').mkdir(parents=True)
(view/'control').mkdir();(view/'evidence').mkdir()
inputs=[]
for index in range(4):
    run=root/'runs'/f'segment_{index:04d}'
    assert (run/'END_EPOCH').exists()
    audit=json.loads((run/'population_audit.json').read_text());assert audit['exact_partition']
    # Real directories with file symlinks preserve rglob inventory semantics.
    # The completed segment files are read in place; no raw copies are made.
    for source in sorted(run.rglob('*')):
        if not source.is_file():continue
        destination=view/'runs'/run.name/source.relative_to(run)
        destination.parent.mkdir(parents=True,exist_ok=True)
        destination.symlink_to(source)
        st=source.stat();inputs.append(dict(path=str(source),bytes=st.st_size,mtime_ns=st.st_mtime_ns))
states=json.loads((root/'runs/segment_0003/checkpoint_manifest.json').read_text())
latest=next(s for s in states if s['cycle']==1902)
assert latest['sha256']=='1fd79b708bbb8ba5547d3c0390b914e63e90d802a377f4989d62ea4a9842d3f2'
(view/'control/latest_checkpoint.json').write_text(json.dumps(latest,indent=2)+'\n')
(out/'input_metadata.json').write_text(json.dumps(inputs,indent=2)+'\n')
(out/'QUALIFICATION.md').write_text(
    '# Partial report pipeline validation\n\n'
    'Completed segments 0–3 only, through audited t=8.803125. This is a software '
    'integration check, not the final t=75 science report or an additional evolution. '
    'The active segment is excluded. Resource totals cover only the input-view '
    'production jobs; they are not the complete campaign accounting. Saved-state '
    'angular validation is still pending. Movies are not regenerated by this check.\n')
command=[sys.executable,str(tooling/'products.py'),'--root',str(view),'--out',str(out/'products'),'--partial']
(out/'command.json').write_text(json.dumps(command,indent=2)+'\n')
with (out/'pipeline.log').open('w') as log:
    result=subprocess.run(command,stdout=log,stderr=subprocess.STDOUT)
assert result.returncode==0,f'partial report pipeline return code {result.returncode}'
p=out/'products';metrics=json.loads((p/'metrics.json').read_text())
assert metrics['cycle']==1902 and abs(metrics['endpoint']-latest['time'])<1e-10
assert len(metrics['source_runs'])==4 and not any('segment_0004' in s for s in metrics['source_runs'])
assert metrics['particles_alive']==4_198_470 and sum(metrics['removed'])==801_530
assert metrics['strict_common_time'] is None and all(x is not None for x in metrics['first_individual_times'])
audit=json.loads((root/'runs/segment_0003/population_audit.json').read_text())
ledger=pd.read_csv(p/'component_ledgers.csv')
last=ledger[(ledger.cycle==1902)&(ledger['mask']==0)].set_index('component')
assert set(last.index)=={0,1,2}
for c,a in enumerate(audit['components']):
    assert int(last.loc[c,'count'])==a['alive']
    assert np.isclose(last.loc[c,'rest_mass'],a['alive_mass'],rtol=2e-10,atol=1e-14)
    assert np.isclose(last.loc[c,'Jz'],a['native_Jz'],rtol=2e-10,atol=1e-12)
assert last.loc[[1,2],'native_energy_unknown_shells'].gt(0).all()
assert last.loc[[1,2],'Ecoord_native'].isna().all()
removed=pd.read_csv(p/'removal_ledgers.csv');assert int(removed['count'].sum())==801_530
accepted=pd.read_csv(p/'accepted_horizons.csv')
assert set(accepted.horizon)=={0,1} and accepted.state_cycle.max()==1902
wave=json.loads((p/'wave_method.json').read_text())
assert {r['radius'] for r in wave['modes']}=={36,40,44},'missing native wave radii'
required=['REPORT.md','four_states.png','four_states.pdf','horizon_mass_spin.png',
          'horizon_mass_spin.pdf','orbit_diagnostics.png','exterior_constraints.csv',
          'crossing_fluxes.csv','timescales.csv','quantitative_evidence.json']
for name in required:assert (p/name).is_file(),name
for row in json.loads((p/'manifest.json').read_text()):
    f=p/row['path'];assert f.parent==p
    assert f.stat().st_size==row['bytes'] and products.sha256(f)==row['sha256']
for row in inputs:
    st=Path(row['path']).stat()
    assert (st.st_size,st.st_mtime_ns)==(row['bytes'],row['mtime_ns']),row['path']
record=dict(status='pass',job_id=os.environ['SLURM_JOB_ID'],source=os.environ['SOURCE_COMMIT'],
    renderer_source=qa['source'],renderer_sha256=qa['tooling_sha256']['products.py'],
    evolution_advances=0,active_segment_excluded=True,endpoint=metrics['endpoint'],cycle=1902,
    audited_alive_counts_rest_weights_Jz_match=True,removal_count_matches=True,
    unknown_native_energies_preserved=True,native_wave_radii=[36,40,44],
    input_metadata_unchanged=True,product_manifest_verified=True,products=str(p),
    qualification='Partial software validation only; no final t75 science or saved-state AH angular-validation claim')
(out/'RESULT.json').write_text(json.dumps(record,indent=2)+'\n')
print(json.dumps(record,indent=2))
