"""Small metadata fixtures for the OS-first guard; no simulation or remote mutation."""
import csv
import json
from pathlib import Path
import tempfile
import unittest
import shlex
from unittest.mock import patch
import os_gate as G

class GateTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup)
        self.root=Path(self.tmp.name);(self.root/'provenance').mkdir()
        self.rows=[dict(case=f'C{i}',seed='1',status='archived_central_horizon_qualified',
                       horizon_t50_status='qualified_archived',horizon_t60_status='qualified_archived')for i in range(40)]
        self.rows += [dict(case='I0',seed=str(i),status='validated_archived',
                          horizon_t50_status='not_applicable',horizon_t60_status='not_applicable')for i in range(5)]
        self.ledger=self.root/'provenance/run_matrix.csv'
        self.write_ledger()
        self.release=self.root/'autogenerated_release/final_release_fixture_build_actual';self.release.mkdir(parents=True)
        self.manifest='a'*64
        self.pipeline=dict(passed=True,epochs=80,cases=40,initializations=5,source_manifest_sha256=self.manifest)
        (self.release/'PIPELINE_VALIDATED.json').write_text(json.dumps(self.pipeline))
        (self.release/'SHA256SUMS').write_text('fixture-seal')
        (self.release/'BUILD_COMPLETE.json').write_text(json.dumps(dict(scientific_checks_passed=True,
            source_manifest_sha256=self.manifest,manifest_sha256=G.digest(self.release/'SHA256SUMS'))))
        self.receipt=self.root/'provenance/final_release_dispatch_fixture/DELIVERY_VERIFIED.json';self.receipt.parent.mkdir()
        self.delivery=dict(all_file_checksums_verified=True,destination=str(self.release),
            source_manifest_sha256=self.manifest,files={'provenance/run_matrix.csv':G.digest(self.ledger)})
        self.write_receipt()
        self.addCleanup(patch.stopall)
        patch.object(G,'OS_ROOT',self.root).start()
        self.queue=patch.object(G,'queue',return_value=[]).start()

    def write_ledger(self):
        with self.ledger.open('w')as stream:
            writer=csv.DictWriter(stream,fieldnames=list(self.rows[0]));writer.writeheader();writer.writerows(self.rows)

    def write_receipt(self):
        self.receipt.write_text(json.dumps(self.delivery))

    def test_complete_numeric_evidence_is_candidate_only(self):
        self.assertTrue(G.inspect()['ready'])
        with self.assertRaises(FileNotFoundError):G.require_release(self.root)

    def test_queued_retry_blocks_release(self):
        self.queue.return_value=['42|os_finer_resume2048|PENDING']
        self.assertFalse(G.inspect()['ready'])

    def test_empty_queue_but_incomplete_science_stays_closed(self):
        self.rows[0]['horizon_t60_status']='pending';self.write_ledger()
        self.assertFalse(G.inspect()['ready'])

    def test_missing_initialization_stays_closed(self):
        self.rows.pop();self.write_ledger();self.assertFalse(G.inspect()['ready'])

    def test_unverified_copy_is_not_completion(self):
        self.delivery['all_file_checksums_verified']=False;self.write_receipt()
        self.assertFalse(G.inspect()['ready'])

    def test_wrong_epoch_count_stays_closed(self):
        self.pipeline['epochs']=79;(self.release/'PIPELINE_VALIDATED.json').write_text(json.dumps(self.pipeline))
        self.assertFalse(G.inspect()['ready'])

    def test_changed_ledger_digest_stays_closed(self):
        self.delivery['files']['provenance/run_matrix.csv']='0'*64;self.write_receipt()
        self.assertFalse(G.inspect()['ready'])

    def test_transport_unknown_never_becomes_ready(self):
        self.queue.side_effect=TimeoutError('fixture transport')
        with self.assertRaises(TimeoutError):G.inspect()

    def test_matching_explicit_owner_completion_release(self):
        evidence=self.root/'evidence';evidence.mkdir()
        (evidence/'OS_PRIORITY_RELEASE.json').write_text(json.dumps(dict(verified_complete=True,
            os_delivery_sha256=G.digest(self.receipt))))
        self.assertTrue(G.require_release(self.root)['ready'])

    def owner_receipt(self):
        evidence=self.root/'evidence';evidence.mkdir()
        state=self.root/'SESSION_STATE.md';state.write_text('Fixture owner final closeout complete, not a mere waiver announcement')
        report=self.root/'REPORT.md';report.write_text('Fixture final report delivered')
        d=dict(verified_complete=True,owner_completion_verified=True,completion_basis='Fixture inspected owner final state and delivered report',
               owner_closeout_evidence=[dict(path=str(p),sha256=G.digest(p))for p in[state,report]])
        path=evidence/'OS_PRIORITY_RELEASE.json';path.write_text(json.dumps(d))
        return path,d

    def test_owner_accepted_closeout_does_not_require_relabelling_waivers(self):
        self.rows[0]['status']='reported_under_user_waiver';self.write_ledger()
        self.owner_receipt()
        self.assertTrue(G.require_release(self.root)['ready'])

    def test_owner_closeout_still_blocked_by_active_retry(self):
        self.owner_receipt();self.queue.return_value=['43|os_retry|RUNNING']
        with self.assertRaises(AssertionError):G.require_release(self.root)

    def test_owner_closeout_requires_unchanged_final_evidence(self):
        self.owner_receipt();(self.root/'REPORT.md').write_text('changed')
        with self.assertRaises(AssertionError):G.require_release(self.root)

    def test_owner_claim_without_final_evidence_refused(self):
        path,d=self.owner_receipt();d['owner_closeout_evidence']=[];path.write_text(json.dumps(d))
        with self.assertRaises(AssertionError):G.require_release(self.root)

class TransportTests(unittest.TestCase):
    def test_remote_format_pipes_are_quoted_not_executed(self):
        with patch.object(G.subprocess,'check_output',return_value='42|os_retry|PENDING\n')as call:
            self.assertEqual(G.queue(),['42|os_retry|PENDING'])
            remote=call.call_args[0][0][-1]
            self.assertEqual(shlex.split(remote),['squeue','-u','jiaxiwu','-h','-o','%i|%j|%T'])

if __name__=='__main__':
    unittest.main()
