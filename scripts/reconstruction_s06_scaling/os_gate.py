"""Read-only OS priority proof. No OS files, jobs or controllers are changed."""
import csv
import hashlib
import json
from pathlib import Path
import shlex
import subprocess

OS_ROOT = Path('/data/jiaxiwu/NRPIC/paper/session_01_os_collapse/convergence')

def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()

def ledger_valid(rows):
    if len(rows) != 45 or len({(r['case'], r['seed']) for r in rows}) != 45:
        return False
    evolved = [r for r in rows if r['case'] != 'I0']
    initials = [r for r in rows if r['case'] == 'I0']
    return (len(evolved) == 40 and len(initials) == 5
        and all(r.get('status') == 'archived_central_horizon_qualified'
                and r.get('horizon_t50_status') == r.get('horizon_t60_status') == 'qualified_archived'
                for r in evolved)
        and all(r.get('status') == 'validated_archived' for r in initials))

def queue(local=False):
    cmd = ['squeue', '-u', 'jiaxiwu', '-h', '-o', '%i|%j|%T']
    if not local:
        cmd = ['ssh', '-o', 'BatchMode=yes', '-o', 'ConnectTimeout=15', 'hpcfund.amd.com', shlex.join(cmd)]
    reply = subprocess.check_output(cmd, text=True, timeout=45)
    return [line for line in reply.splitlines() if len(line.split('|')) == 3
            and line.split('|')[1].startswith('os_')]

def inspect():
    state = dict(ready=False, outstanding_os_jobs=queue(), reason='OS tests still active')
    owner_state=OS_ROOT/'SESSION_STATE.md'
    if owner_state.exists():
        state.update(owner_state_sha256=digest(owner_state),owner_header=owner_state.read_text()[:1500])
    ledger = OS_ROOT / 'provenance/run_matrix.csv'
    if not ledger.exists():
        return dict(state, reason='OS canonical ledger unavailable')
    with ledger.open() as stream:
        rows = list(csv.DictReader(stream))
    state['qualified_evolutions'] = sum(r.get('status') == 'archived_central_horizon_qualified' for r in rows)
    if state['outstanding_os_jobs'] or not ledger_valid(rows):
        return state
    # Follow new OS release versions automatically; never freeze today's job IDs.
    for receipt in sorted((OS_ROOT / 'provenance').glob('final_release_dispatch_*/DELIVERY_VERIFIED.json'),
                          key=lambda p: p.stat().st_mtime, reverse=True):
        d = json.loads(receipt.read_text())
        if not d.get('all_file_checksums_verified'):
            continue
        release = Path(d['destination']).resolve()
        if release.parent != (OS_ROOT / 'autogenerated_release').resolve():
            continue
        pipeline = json.loads((release / 'PIPELINE_VALIDATED.json').read_text())
        seal = json.loads((release / 'BUILD_COMPLETE.json').read_text())
        if (pipeline.get('passed') and pipeline.get('epochs') == 80 and pipeline.get('cases') == 40
            and pipeline.get('initializations') == 5 and seal.get('scientific_checks_passed')
            and pipeline['source_manifest_sha256'] == seal['source_manifest_sha256'] == d['source_manifest_sha256']
            and digest(release / 'SHA256SUMS') == seal['manifest_sha256']
            and digest(ledger) == d['files']['provenance/run_matrix.csv']):
            return dict(state, ready=True, reason='80 OS epochs scientifically released; no queued/running OS jobs',
                        delivery_receipt=str(receipt), delivery_sha256=digest(receipt),
                        ledger_sha256=digest(ledger), release=str(release),
                        owner_visual_review_pending=d.get('visual_review_pending', True))
    return dict(state, reason='OS success ledger exists but verified final release not yet delivered')

def require_release(root):
    root = Path(root)
    release = json.loads((root / 'evidence/OS_PRIORITY_RELEASE.json').read_text())
    if not release.get('verified_complete'):
        raise RuntimeError('OS completion has not been verified')
    # OS's owner may explicitly change its own finish criteria. Accept a documented
    # owner closeout without relabelling waived OS results as strictly qualified.
    # The resumed agent must inspect actual final delivery/closure, not the waiver
    # announcement alone, and bind at least two real OS records to its receipt.
    if release.get('owner_completion_verified') is True:
        assert not queue(), 'OS jobs are still active'
        proofs=release.get('owner_closeout_evidence',[])
        assert len(proofs)>=2 and len({p['path']for p in proofs})==len(proofs)
        for proof in proofs:
            path=Path(proof['path']).resolve()
            assert OS_ROOT.resolve() in path.parents and path.is_file()
            assert digest(path)==proof['sha256'],'OS closeout evidence changed'
        assert release.get('completion_basis'), 'Describe the actual OS owner completion'
        return dict(ready=True,reason='OS owner final closeout independently inspected and hash-bound',
                    owner_closeout_evidence=proofs,outstanding_os_jobs=[],completion_basis=release['completion_basis'])
    current = inspect()
    if not current['ready'] or current['delivery_sha256'] != release['os_delivery_sha256']:
        raise RuntimeError('OS priority gate is closed or changed')
    return current
